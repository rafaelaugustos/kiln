func TestNextDSTOracle(t *testing.T) {
	t.Parallel()
	specs := []string{
		"* * * * *", "0 * * * *", "30 * * * *", "*/15 * * * *", "*/7 * * * *", "0 */2 * * *", "10 1-3/1 * * *",
		"0 0 * * *", "30 23 * * *", "0 1 * * *", "30 1 * * *", "45 1 * * *", "0 2 * * *", "15 2 * * *",
		"30 2 * * *", "0 2,3 * * *", "0 1-3 * * *", "*/30 1 * * *", "*/10 2 * * *", "0,30 0-3 * * *",
	}
	for _, z := range []struct {
		zone  string
		dates []string
	}{
		{"America/New_York", []string{"2026-03-08", "2026-11-01"}},
		{"Europe/London", []string{"2026-03-29", "2026-10-25"}},
		{"Australia/Lord_Howe", []string{"2026-04-05", "2026-10-04"}},
		{"America/Sao_Paulo", []string{"2018-11-04", "2019-02-17"}},
	} {
		loc := load(t, z.zone)
		for _, date := range z.dates {
			d, err := time.ParseInLocation(time.DateOnly, date, loc)
			if err != nil {
				t.Fatal(err)
			}
			from, to := d.AddDate(0, 0, -2), d.AddDate(0, 0, 2)
			for _, spec := range specs {
				s := mustParse(t, spec)
				want := oracle(s, from, to)
				var got []time.Time
				for x := s.Next(from); x.Before(to); x = s.Next(x) {
					got = append(got, x)
				}
				if len(got) != len(want) {
					t.Errorf("%s %s %q: %d activations, want %d", z.zone, date, spec, len(got), len(want))
				}
				for i := range min(len(got), len(want)) {
					if !got[i].Equal(want[i]) {
						t.Errorf("%s %s %q: activation %d = %s, want %s", z.zone, date, spec, i,
							got[i].Format(time.RFC3339), want[i].Format(time.RFC3339))
						break
					}
				}
			}
		}
	}
}

func oracle(s *Schedule, from, to time.Time) []time.Time {
	wall := func(t time.Time) time.Time {
		return time.Date(t.Year(), t.Month(), t.Day(), t.Hour(), t.Minute(), 0, 0, time.UTC)
	}
	hit := func(w time.Time) bool {
		return s.minute>>w.Minute()&1 != 0 && s.hour>>w.Hour()&1 != 0
	}
	seen := func(x, w time.Time) bool {
		for d := 15 * time.Minute; d <= 3*time.Hour; d += 15 * time.Minute {
			if wall(x.Add(-d)).Equal(w) {
				return true
			}
		}
		return false
	}
	var out []time.Time
	for x := from.Add(time.Minute); x.Before(to); x = x.Add(time.Minute) {
		w := wall(x)
		fire := hit(w) && (s.interval || !seen(x, w))
		if !s.interval {
			for g := wall(x.Add(-time.Minute)).Add(time.Minute); g.Before(w); g = g.Add(time.Minute) {
				fire = fire || hit(g)
			}
		}
		if fire {
			out = append(out, x)
		}
	}
	return out
}
